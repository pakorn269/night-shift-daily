export const localizeCaseTh = (incident: PublicCase): PublicCase => {
  const th = TH_CASES[incident.id];
  if (!th) {
    return incident;
  }

  return {
    ...incident,
    title: th.title,
    teaser: th.teaser,
    category: th.category,
    severity: th.severity,
    summary: th.summary,
    protocolRule: th.protocolRule,
    shortRule: th.shortRule,
    evidence: incident.evidence.map((row) => {
      const thRow = th.evidence[row.id];
      if (!thRow) {
        return row;
      }
      return {
        ...row,
        shortLabel: thRow.shortLabel,
        shortClue: thRow.shortClue,
        detail: thRow.detail,
        whisper: thRow.whisper,
      };
    }),
    actions: incident.actions.map((action) => {
      const thAction = th.actions[action.id];
      if (!thAction) {
        return action;
      }
      return {
        ...action,
        label: thAction.label,
        description: thAction.description,
      };
    }),
  };
};

export const buildThaiEvaluationCopy = (
  authoredCase: AuthoredCase,
  selectedEvidenceId: string,
  selectedActionId: string,
  actionCorrect: boolean,
  fallbackEn: EvaluationCopy
): EvaluationCopy => {
  const th = TH_CASES[authoredCase.id];
  if (!th) {
    return fallbackEn;
  }

  const correctEvTh = th.evidence[authoredCase.solution.evidenceId];
  const selectedEvTh = th.evidence[selectedEvidenceId];
  const correctActTh = th.actions[authoredCase.solution.actionId];
  const selectedActTh = th.actions[selectedActionId];
  const wrongNote = th.wrongActionFeedback[selectedActionId];

  const selectedActionLabel =
    selectedActTh?.label ?? fallbackEn.selectedActionLabel;

  return {
    correctEvidenceShortLabel:
      correctEvTh?.shortLabel ?? fallbackEn.correctEvidenceShortLabel,
    selectedEvidenceShortLabel:
      selectedEvTh?.shortLabel ?? fallbackEn.selectedEvidenceShortLabel,
    correctActionLabel: correctActTh?.label ?? fallbackEn.correctActionLabel,
    selectedActionLabel,
    evidenceExplanation: th.evidenceExplanation,
    actionExplanation: th.actionExplanation,
    selectedActionNote: actionCorrect
      ? th.actionCorrectNote
      : (wrongNote ??
        `คุณเลือก "${selectedActionLabel}" ซึ่งไม่สามารถหยุดความผิดปกติที่กำลังเกิดขึ้นได้`),
  };
};
